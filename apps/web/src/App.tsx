import { useCallback, useEffect, useRef, useState } from 'react';
import {
  createConversation,
  deleteDocument,
  getDocumentInspection,
  listDocuments,
  sendMessage,
  uploadDocument,
  type DocumentSummary
} from './api/client.js';
import { ChatPanel } from './components/ChatPanel.js';
import { DocumentDetail } from './components/DocumentDetail.js';
import { DocumentList } from './components/DocumentList.js';
import { DocumentUploader } from './components/DocumentUploader.js';

const pollMs = 2000;

export function App() {
  const [documents, setDocuments] = useState<DocumentSummary[]>([]);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const conversationId = useRef<Promise<string> | null>(null);

  async function handleDelete(id: string) {
    await deleteDocument(id);
    setDocuments((current) => current.filter((document) => document.id !== id));
    setSelectedId((current) => (current === id ? null : current));
  }

  const refresh = useCallback(async () => {
    try {
      setDocuments(await listDocuments());
    } catch {
      /* keep the last known list; the next poll retries */
    }
  }, []);

  useEffect(() => {
    void refresh();
  }, [refresh]);

  const inFlight = documents.some(
    (document) => document.status === 'pending' || document.status === 'processing'
  );
  useEffect(() => {
    if (!inFlight) return;
    const timer = setInterval(() => void refresh(), pollMs);
    return () => clearInterval(timer);
  }, [inFlight, refresh]);

  const hasReady = documents.some((document) => document.status === 'ready');

  async function handleUpload(file: File) {
    const document = await uploadDocument(file);
    setDocuments((current) => [document, ...current.filter((item) => item.id !== document.id)]);
    return document;
  }

  async function ask(question: string) {
    conversationId.current ??= createConversation().then((conversation) => conversation.id);
    try {
      return await sendMessage(await conversationId.current, question);
    } catch (error) {
      conversationId.current = null;
      throw error;
    }
  }

  return (
    <main>
      <header>
        <span className="eyebrow">TENANT KNOWLEDGE BASE</span>
        <h1>Ask your documents.</h1>
        <p>
          Answers are generated by a replaceable agent runtime and cite retrieved source chunks.
        </p>
      </header>
      <section className="panel documents-panel">
        <DocumentUploader onUpload={handleUpload} />
        <DocumentList documents={documents} selectedId={selectedId} onSelect={setSelectedId} />
      </section>
      {selectedId && (
        <DocumentDetail
          documentId={selectedId}
          load={getDocumentInspection}
          onDelete={handleDelete}
          onClose={() => setSelectedId(null)}
        />
      )}
      <ChatPanel
        ask={ask}
        disabled={!hasReady}
        disabledReason="Chat unlocks once at least one document is ready."
      />
    </main>
  );
}
